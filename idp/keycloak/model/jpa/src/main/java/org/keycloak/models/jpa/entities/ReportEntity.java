package org.keycloak.models.jpa.entities;

import javax.persistence.*;

/**
 * @author <a href="mailto:bill@burkecentral.com">Bill Burke</a>
 * @version $Revision: 1 $
 */
@Entity
@Table(name="REPORT", uniqueConstraints = {@UniqueConstraint(columnNames = {"REALM_ID"})})
@NamedQueries({
        @NamedQuery(name="getReports", query="select report from ReportEntity report where report.realmId = :realm by report.createdDate"),
        @NamedQuery(name="getReportById", query="select report from ReportEntity report where report.id = :id")
})
public class ReportEntity {

    @Id
    @Column(name="ID", length = 36)
    @Access(AccessType.PROPERTY) // we do this because relationships often fetch id, but not entity.  This avoids an extra SQL
    private String id;
    @Column(name = "REPORT_TYPE")
    private String reportType;

    @Column(name = "REALM_ID")
    protected String realmId;

    @Column(name="FILE_NAME")
    private String fileName;

    @Column(name="REQUESTED_BY")
    private String requestedBy;

    @Column(name="STATUS")
    private String status;

    @Column(name = "CREATED_DATE")
    private Long createdDate;

    public String getRealmId() {
        return realmId;
    }

    public void setRealmId(String realmId) {
        this.realmId = realmId;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getReportType() {
        return reportType;
    }

    public void setReportType(String reportType) {
        this.reportType = reportType;
    }

    public String getFileName() {
        return fileName;
    }

    public void setFileName(String fileName) {
        this.fileName = fileName;
    }

    public String getRequestedBy() {
        return requestedBy;
    }

    public void setRequestedBy(String requestedBy) {
        this.requestedBy = requestedBy;
    }

    public Long getCreatedDate() {
        return createdDate;
    }

    public void setCreatedDate(Long createdDate) {
        this.createdDate = createdDate;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null) return false;
        if (!(o instanceof ReportEntity)) return false;

        ReportEntity that = (ReportEntity) o;

        if (!id.equals(that.getId())) return false;

        return true;
    }

    @Override
    public int hashCode() {
        return id.hashCode();
    }

}
