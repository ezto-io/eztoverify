import org.keycloak.models.KeycloakSessionFactory;
import org.keycloak.services.resource.ezto.EztoPublicRealmResourceProvider;
import org.keycloak.services.resource.ezto.EztoPublicRealmResourceProviderFactory;

public class DeepLinkingProviderFactory implements EztoPublicRealmResourceProviderFactory {
    public static final String ID = "deeplink";
    @Override
    public EztoPublicRealmResourceProvider create(KeycloakSession session) {
        return new DeepLinkingProvider(session);
    }

    @Override
    public void init(Config.Scope config) {
        // NOP
    }

    @Override
    public void postInit(KeycloakSessionFactory factory) {
        // NOP
    }

    @Override
    public void close() {
        // NOP
    }

    @Override
    public String getId() {
        return ID;
    }
}
